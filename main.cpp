#include <iostream>
#include <clocale>

using namespace std;

int main() {
    // Настройка локализации для корректного вывода кириллицы в консоли
    setlocale(LC_ALL, "Russian");

    cout << "--- КАЛЬКУЛЯТОР ПРИЗЫВА СКЕЛЕТОВ ---\n\n";

    // Инициализация переменных для хранения исходных данных
    int mana = 0;
    int cost = 0;

    // Ввод исходных данных через стандартный поток std::cin
    cout << "Введите текущий запас маны: ";
    cin >> mana;

    cout << "Введите стоимость призыва одного скелета: ";
    cin >> cost;

    // Блок программной валидации входящих потоков данных.
    // Проверка логических условий: мана не должна быть отрицательной,
    // а стоимость призыва должна быть строго больше нуля (защита от деления на ноль).
    if (mana < 0 || cost <= 0) {
        cout << "\n[ОШИБКА] Мана не может быть меньше нуля, а стоимость призыва должна быть больше нуля.\n";
        return 1; // Аварийное завершение программы с кодом ошибки
    }

    // Арифметический расчет основных показателей
    int army = mana / cost;       // Вычисление максимального размера армии (целочисленное деление)
    int rest_mana = mana % cost;  // Вычисление остатка ресурса (взятие остатка от деления)

    // Логическое ветвление для определения и вывода статуса ритуала
    if (army > 0) {
        cout << "\n[РИТУАЛ ЗАВЕРШЕН] Армия призвана!\n";
    } else {
        cout << "\n[ВНИМАНИЕ] Недостаточно маны для призыва даже одного скелета.\n";
    }

    // Вывод структурированных результатов вычислений в стандартный поток std::cout
    cout << "Максимальный размер армии: " << army << " скелетов.\n";
    cout << "Остаток маны: " << rest_mana << " ед.\n";

    return 0; // Успешное завершение работы программы
}
